/**
 * Bundle sim/* into online-sim.js (IIFE) using the local typescript package.
 * Avoids requiring a separate esbuild install.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import ts from "typescript";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const simDir = path.join(root, "sim");
const outFile = path.join(root, "online-sim.js");

const order = [
  "constants.ts",
  "math.ts",
  "upgrades.ts",
  "tyres.ts",
  "collision.ts",
  "kart.ts",
  "raceOnline.ts",
  "tracks.ts",
  "browser-entry.ts",
];

/** Remove imports only — leave `export type` for the TS eraser. */
function stripImports(code) {
  return code.replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, "");
}

/** After transpile, drop remaining export keywords (types already erased). */
function stripExports(js) {
  return js
    .replace(/^export\s+default\s+/gm, "")
    .replace(/^export\s+/gm, "")
    .replace(/export\s*\{[\s\S]*?\};?\s*$/gm, "");
}

function transpile(src) {
  const js = ts.transpileModule(stripImports(src), {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2020,
      removeComments: true,
    },
  }).outputText;
  return stripExports(js);
}

const bakesPath = path.join(simDir, "tracks", "bakes.json");
const bakes = fs.readFileSync(bakesPath, "utf8");

let body = "";
body += `var bakesJson = ${bakes};\n`;

for (const file of order) {
  if (file === "browser-entry.ts") continue;

  let src = fs.readFileSync(path.join(simDir, file), "utf8");

  if (file === "tracks.ts") {
    src = src.replace(/import bakesJson from ["'][^"']+["'];?/, "");
  }

  if (file === "raceOnline.ts") {
    src = src.replace(/import \{ encodeState[\s\S]*?\} from ["']\.\.\/party\/netcodec["'];?/, "");
    src =
      `
function encodeState(state, prev) {
  if (typeof OnlineCodec !== "undefined" && OnlineCodec.encodeState) return OnlineCodec.encodeState(state, prev);
  return new ArrayBuffer(0);
}
` + src;
  }

  body += "\n// ---- " + file + " ----\n" + transpile(src);
}

const wrapped = `/**
 * Auto-generated by scripts/build-online-sim.mjs — do not edit by hand.
 * Shared online physics for browser prediction (mirrors sim/).
 */
(function (global) {
  'use strict';
${body}

  global.OnlineSim = {
    ONLINE_PROTOCOL: ONLINE_PROTOCOL,
    TRACK_BAKE_VERSION: TRACK_BAKE_VERSION,
    FIXED_DT: FIXED_DT,
    SIM_HZ: SIM_HZ,
    STATE_HZ: STATE_HZ,
    INPUT_HZ: typeof INPUT_HZ !== "undefined" ? INPUT_HZ : 30,
    STEPS_PER_INPUT: typeof STEPS_PER_INPUT !== "undefined" ? STEPS_PER_INPUT : 2,
    defaultUpgrades: defaultUpgrades,
    sanitizeUpgrades: sanitizeUpgrades,
    createKart: createKart,
    stepKart: stepKart,
    emptyInput: emptyInput,
    applyNetPose: applyNetPose,
    cloneKartPose: cloneKartPose,
    copyKartState: copyKartState,
    resolveKartCollisions: resolveKartCollisions,
    OnlineRaceSim: OnlineRaceSim,
    loadTrackBake: loadTrackBake,
    listTrackIds: listTrackIds,
    SimKart: SimKart
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(outFile, wrapped);
console.log("Wrote", outFile, "(" + Math.round(wrapped.length / 1024) + " KB)");
